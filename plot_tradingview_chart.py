# 3. SPYDER IN-CONSOLE PLOT (MATPLOTLIB)
# =====================================================================
def plot_spyder_native(df, alert_times, target_date, timeframe_label):
    fig, ax = plt.subplots(figsize=(15, 7), facecolor='#131722')
    ax.set_facecolor('#131722')
    
    width = 0.6
    for idx, row in df.iterrows():
        color = '#089981' if row['close'] >= row['open'] else '#F23645'
        # Wick
        ax.plot([idx, idx], [row['low'], row['high']], color=color, linewidth=1.1)
        # Body
        body_bottom = min(row['open'], row['close'])
        body_height = max(abs(row['close'] - row['open']), 0.5)
        ax.add_patch(Rectangle((idx - width/2, body_bottom), width, body_height, facecolor=color, edgecolor=color))
        
    # Plot alert markers
    if alert_times:
        alert_indices = df[df['time'].isin(alert_times)].index
        ax.scatter(alert_indices, df.loc[alert_indices, 'low'] - 6.0, color='#FF9800', marker='^', s=45, zorder=5, label='Vol Alert')

    # Axis styling
    ax.yaxis.tick_right()
    ax.yaxis.set_label_position("right")
    ax.grid(True, color='#1E222D', linestyle='-', linewidth=0.8)
    ax.spines['bottom'].set_color('#2A2E39')
    ax.spines['top'].set_visible(False)
    ax.spines['left'].set_visible(False)
    ax.spines['right'].set_color('#2A2E39')
    ax.tick_params(colors='#787B86', which='both', labelsize=9)

    # Dynamic time labels based on number of candles
    step = max(1, len(df) // 10)
    tick_indices = list(range(0, len(df), step))
    ax.set_xticks(tick_indices)
    ax.set_xticklabels([df['time'].iloc[i][:5] for i in tick_indices])
    ax.set_xlim(-1, len(df))

    open_p, close_p = df['open'].iloc[0], df['close'].iloc[-1]
    chg = close_p - open_p
    sign = "+" if chg >= 0 else ""
    ax.set_title(
        f"NIFTY 50 · {timeframe_label} · NSE ({target_date})   O: {open_p:.2f}  H: {df['high'].max():.2f}  L: {df['low'].min():.2f}  C: {close_p:.2f}  ({sign}{chg:.2f})",
        loc='left', color='#D1D4DC', fontsize=11, fontweight='bold', pad=12
    )

    plt.tight_layout()
    plt.show()

