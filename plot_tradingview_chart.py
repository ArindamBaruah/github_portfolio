def find_spot_file(base_dir, target_date):
    """Locates the spot CSV for target_date across nested directories."""
    for root, _, files in os.walk(base_dir):
        for f in files:
            if f.lower().endswith(".csv") and target_date in f:
                return os.path.join(root, f)
    return None

def find_alerts_file(base_dir, target_date):
    """Searches for simulation alert Excel files generated by the ML pipeline."""
    candidates = [
        f"alerts_{target_date}.xlsx",
        f"nifty_vol_simulation_{target_date}.xlsx",
        f"nifty_vol_alerts_{target_date}.xlsx"
    ]
    for c in candidates:
        full_path = os.path.join(base_dir, c)
        if os.path.exists(full_path):
            return full_path
    return None

def load_session_data(target_date):
    spot_file = find_spot_file(SPOT_BASE_DIR, target_date)
    if not spot_file:
        raise FileNotFoundError(f"No spot CSV found for date {target_date} in {SPOT_BASE_DIR}")
    
    print(f"[{datetime.now().strftime('%H:%M:%S')}] Loading spot data: {spot_file}")
    df = pd.read_csv(spot_file)
    df.columns = [c.strip().lower() for c in df.columns]
    df['time'] = df['time'].astype(str).str.strip()
    
    # Filter NSE market hours (09:15 to 15:30)
    df = df[(df['time'] >= '09:15:00') & (df['time'] <= '15:30:00')].sort_values('time').reset_index(drop=True)
    for col in ['open', 'high', 'low', 'close']:
        df[col] = df[col].astype(float)
        
    # Check for alerts file
    alert_times = []
    if OVERLAY_ALERTS:
        alert_path = find_alerts_file(ALERTS_BASE_DIR, target_date)
        if alert_path:
            print(f"[{datetime.now().strftime('%H:%M:%S')}] Found alert markers: {alert_path}")
            adf = pd.read_excel(alert_path)
            adf.columns = [c.strip().upper() for c in adf.columns]
            status_col = 'ALERT STATUS' if 'ALERT STATUS' in adf.columns else 'ALERT'
            if status_col in adf.columns and 'TIME' in adf.columns:
                spike_rows = adf[adf[status_col].astype(str).str.contains("IMMINENT|SPIKE", case=False, na=False)]
                alert_times = spike_rows['TIME'].astype(str).str.strip().tolist()
                print(f"[{datetime.now().strftime('%H:%M:%S')}] Overlaying {len(alert_times)} imminent volatility triggers.")
                
    return df, alert_times

def resample_data(df, alert_times, target_date, timeframe):
    """Aggregates 1-minute OHLCV data into higher timeframes (e.g., '5min', '15min', '60min')."""
    tf_mapping = {'5': '5min', '15': '15min', '30': '30min', '60': '60min', '1h': '1H'}
    norm_tf = tf_mapping.get(str(timeframe).lower(), timeframe)
    
    # Create datetime index for resampling
    df_copy = df.copy()
    df_copy['dt'] = pd.to_datetime(target_date + ' ' + df_copy['time'], format='%d_%m_%Y %H:%M:%S')
    df_copy.set_index('dt', inplace=True)
    
    # Resample OHLC data
    agg_dict = {'open': 'first', 'high': 'max', 'low': 'min', 'close': 'last'}
    df_resampled = df_copy.resample(norm_tf).agg(agg_dict).dropna().reset_index()
    df_resampled['time'] = df_resampled['dt'].dt.strftime('%H:%M:%S')
    df_resampled.drop(columns=['dt'], inplace=True)
    
    # Map alert times to the corresponding resampled candles
    new_alert_times = []
    if alert_times:
        alert_dts = [pd.to_datetime(target_date + ' ' + t, format='%d_%m_%Y %H:%M:%S') for t in alert_times]
        delta = pd.to_timedelta(norm_tf)
        
        for _, row in df_resampled.iterrows():
            bar_start = pd.to_datetime(target_date + ' ' + row['time'], format='%d_%m_%Y %H:%M:%S')
            bar_end = bar_start + delta
            if any(bar_start <= adt < bar_end for adt in alert_dts):
                new_alert_times.append(row['time'])
                
    return df_resampled, norm_tf, new_alert_times

