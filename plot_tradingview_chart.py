def main(timeframe='5min'):
    """
    Main entry point for generating charts with a specified timeframe.
    Examples: main('5min'), main('15min'), main('60min') or main('1H')
    """
    df_raw, alerts_raw = load_session_data(TARGET_OOS_DATE)
    df_session, tf_label, filtered_alerts = resample_data(df_raw, alerts_raw, TARGET_OOS_DATE, timeframe)
    
    plot_spyder_native(df_session, filtered_alerts, TARGET_OOS_DATE, tf_label)
    generate_tradingview_html(df_session, filtered_alerts, TARGET_OOS_DATE, tf_label)

if __name__ == "__main__":
    # You can change this argument to '5min', '15min', '60min', etc.
    main(timeframe='5min')